"""
Alert Engine — Core business logic for alert lifecycle management.

Handles alert creation with deduplication, strict lifecycle state transitions,
assignment with username-resolved audit trails, and comment management.
"""
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, and_
from datetime import datetime, timezone, timedelta
from typing import Optional
from fastapi import HTTPException, status

from app.models.alert import Alert, AlertComment
from app.models import SecurityEvent, User
from app.utils.audit import log_alert_action

# ── System Actor ──────────────────────────────────────────────────────────────
# Used for automatically generated actions (e.g. rule-triggered alerts).
# actor_id=None means "system" in audit history — no database user is assumed.
SYSTEM_ACTOR_ID = None

# ── Allowed Lifecycle State Transitions ───────────────────────────────────────
# Maps each current status to the set of statuses it may transition to.
VALID_TRANSITIONS = {
    "new":           {"acknowledged", "escalated"},
    "acknowledged":  {"investigating", "escalated"},
    "investigating": {"resolved", "escalated"},
    "escalated":     {"resolved"},
    "resolved":      {"closed"},
    "closed":        set(),  # terminal state
}


def validate_transition(old_status: str, new_status: str) -> None:
    """
    Validate that a state transition is allowed by the lifecycle rules.
    Raises HTTPException 422 if the transition is invalid.
    """
    if old_status == new_status:
        return  # no-op transitions are silently allowed

    allowed = VALID_TRANSITIONS.get(old_status, set())
    if new_status not in allowed:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Invalid state transition: '{old_status}' → '{new_status}'. "
                   f"Allowed transitions from '{old_status}': {sorted(allowed) if allowed else 'none (terminal state)'}."
        )


async def get_alert(session: AsyncSession, alert_id: int, org_id: int) -> Optional[Alert]:
    query = select(Alert).where(and_(Alert.id == alert_id, Alert.org_id == org_id))
    result = await session.execute(query)
    return result.scalars().first()


async def _resolve_username(session: AsyncSession, user_id: Optional[int]) -> str:
    """Resolve a user_id to a username string for audit trail readability."""
    if user_id is None:
        return "system"
    user = await session.scalar(select(User).where(User.id == user_id))
    return user.username if user else f"user#{user_id}"


async def create_or_dedup_alert(
    session: AsyncSession,
    org_id: int,
    title: str,
    severity: str,
    priority: str = "P3",
    source: str = "manual",
    rule_id: Optional[int] = None,
    event_id: Optional[int] = None,
    source_ip: Optional[str] = None,
    destination_ip: Optional[str] = None,
    description: Optional[str] = None,
    dedup_window_minutes: int = 5,
    actor_id: Optional[int] = SYSTEM_ACTOR_ID,
) -> Alert:
    """
    Creates a new alert or deduplicates if an identical alert was triggered recently.

    When actor_id is None (SYSTEM_ACTOR_ID), the audit history records the action
    as a system-generated event with no FK to the users table.
    """
    dedup_key = f"{rule_id or 'none'}_{source_ip or 'none'}_{title}"

    # Check for dedup within window
    cutoff = datetime.now(timezone.utc) - timedelta(minutes=dedup_window_minutes)

    query = select(Alert).where(
        and_(
            Alert.org_id == org_id,
            Alert.dedup_key == dedup_key,
            Alert.created_at >= cutoff,
            Alert.status.notin_(["resolved", "closed"])
        )
    ).order_by(Alert.created_at.desc())

    result = await session.execute(query)
    existing_alert = result.scalars().first()

    if existing_alert:
        existing_alert.dedup_count += 1
        existing_alert.updated_at = datetime.now(timezone.utc)
        return existing_alert

    # Create new
    new_alert = Alert(
        org_id=org_id,
        title=title,
        description=description,
        severity=severity,
        priority=priority,
        status="new",
        source=source,
        rule_id=rule_id,
        event_id=event_id,
        source_ip=source_ip,
        destination_ip=destination_ip,
        dedup_key=dedup_key,
        dedup_count=1
    )

    session.add(new_alert)
    await session.flush()  # flush to get ID

    is_system = actor_id is SYSTEM_ACTOR_ID or actor_id is None
    log_alert_action(
        session=session,
        alert_id=new_alert.id,
        actor_id=actor_id,  # None for system-generated
        action="created",
        details="Alert automatically generated by system" if is_system else "Alert manually created"
    )

    return new_alert


async def change_alert_status(
    session: AsyncSession,
    alert: Alert,
    new_status: str,
    actor_id: int,
    details: Optional[str] = None
):
    """
    Transition an alert to a new lifecycle status.
    Validates the transition against the allowed state machine before applying.
    """
    old_status = alert.status
    if old_status == new_status:
        return alert

    # Enforce lifecycle rules
    validate_transition(old_status, new_status)

    alert.status = new_status
    alert.updated_at = datetime.now(timezone.utc)

    if new_status == "acknowledged":
        alert.acknowledged_at = datetime.now(timezone.utc)
    elif new_status == "resolved":
        alert.resolved_at = datetime.now(timezone.utc)
    elif new_status == "closed":
        alert.closed_at = datetime.now(timezone.utc)

    log_alert_action(
        session=session,
        alert_id=alert.id,
        actor_id=actor_id,
        action="status_changed",
        old_value=old_status,
        new_value=new_status,
        details=details
    )
    return alert


async def assign_alert(
    session: AsyncSession,
    alert: Alert,
    user_id: int,
    actor_id: int
):
    """
    Assign an alert to a user. Records both previous and new assignee
    usernames in the audit trail for readability.
    """
    old_assignee_name = await _resolve_username(session, alert.assigned_to)
    new_assignee_name = await _resolve_username(session, user_id)

    alert.assigned_to = user_id
    alert.assigned_at = datetime.now(timezone.utc)

    # Auto-acknowledge on first assignment if still in 'new' state
    if alert.status == "new":
        alert.status = "acknowledged"
        alert.acknowledged_at = datetime.now(timezone.utc)

    alert.updated_at = datetime.now(timezone.utc)

    log_alert_action(
        session=session,
        alert_id=alert.id,
        actor_id=actor_id,
        action="assigned",
        old_value=old_assignee_name,
        new_value=new_assignee_name,
        details=f"Reassigned from {old_assignee_name} to {new_assignee_name}"
    )
    return alert


async def add_alert_comment(
    session: AsyncSession,
    alert_id: int,
    author_id: int,
    content: str
) -> AlertComment:
    comment = AlertComment(
        alert_id=alert_id,
        author_id=author_id,
        content=content
    )
    session.add(comment)
    await session.flush()

    log_alert_action(
        session=session,
        alert_id=alert_id,
        actor_id=author_id,
        action="commented",
        details="Added a comment"
    )
    return comment
